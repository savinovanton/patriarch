#!/usr/bin/env python3
"""Generate constant lookup tables used by the simulation (floating point is fine HERE: this runs
offline, and the resulting integers are committed, so the game itself stays float-free).

Currently generates:
  src/core/include/pat/core/detail/sigmoid_table.hpp
      sigmoid(x) = 1 / (1 + e^-x) for x in [-8, 8], step 1/16, Q16.16 raw values (257 entries).

Usage:
    python tools/gen_tables.py            # rewrite the generated headers
    python tools/gen_tables.py --check    # exit 1 if the committed headers differ from the generated ones
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SIGMOID_HEADER = ROOT / "src" / "core" / "include" / "pat" / "core" / "detail" / "sigmoid_table.hpp"

POINTS_PER_UNIT = 16
RANGE = 8


def sigmoid_header() -> str:
    count = 2 * RANGE * POINTS_PER_UNIT + 1
    values = []
    for i in range(count):
        x = -float(RANGE) + i / POINTS_PER_UNIT
        values.append(int(round(65536.0 / (1.0 + math.exp(-x)))))

    lines = [
        "#pragma once",
        "",
        "// GENERATED by tools/gen_tables.py - do not edit by hand.",
        "// sigmoid(x) = 1 / (1 + e^-x) for x in [-8, 8] with step 1/16, stored as Q16.16 raw values.",
        "",
        "#include <array>",
        "#include <cstdint>",
        "",
        "// clang-format off",
        "namespace pat::core::detail {",
        "",
        f"inline constexpr int kSigmoidTableSteps = {POINTS_PER_UNIT};       // table points per unit",
        f"inline constexpr int kSigmoidTableRange = {RANGE};        // covers [-{RANGE}, {RANGE}]",
        "",
        f"inline constexpr std::array<std::int32_t, {count}> kSigmoidTable = {{{{",
    ]
    for i in range(0, count, 8):
        lines.append("    " + ", ".join(str(v) for v in values[i : i + 8]) + ",")
    lines += ["}};", "", "}  // namespace pat::core::detail", "// clang-format on", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="verify committed files instead of writing")
    args = parser.parse_args(argv)

    expected = sigmoid_header()
    if args.check:
        actual = SIGMOID_HEADER.read_text(encoding="utf-8").replace("\r\n", "\n") if SIGMOID_HEADER.exists() else ""
        if actual != expected:
            print(f"{SIGMOID_HEADER} is out of date; run tools/gen_tables.py", file=sys.stderr)
            return 1
        print("generated tables are up to date.")
        return 0

    SIGMOID_HEADER.write_text(expected, encoding="utf-8", newline="\n")
    print(f"wrote {SIGMOID_HEADER}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
