def find_board(boards: list[dict[str, Any]], spec: str) -> dict[str, Any]:
    """A top-level board by exact name, or by number ("15" matches "15 / ...") or by name prefix ending in '/ '."""
    exact = [b for b in boards if b.get("name") == spec]
    if len(exact) == 1:
        return exact[0]
    if len(exact) > 1:
        raise SnapshotError(f"board name {spec!r} is not unique ({len(exact)} boards)")
    prefix = spec if spec.endswith("/ ") else (spec + " / " if re.fullmatch(r"\d+", spec) else spec)
    found = [b for b in boards if str(b.get("name", "")).startswith(prefix)]
    if len(found) == 1:
        return found[0]
    if not found:
        raise SnapshotError(f"no board matches {spec!r}")
    raise SnapshotError(f"board spec {spec!r} is ambiguous: " + ", ".join(repr(b["name"]) for b in found))


def export_boards(snapshot: Snapshot, page: dict[str, Any], specs: list[str]) -> list[tuple[str, list[dict[str, Any]]]]:
    exporter = BoardExporter(snapshot, page)
    boards = exporter.top_level_boards()
    result = []
    for spec in specs:
        board = find_board(boards, spec)
        result.append((str(board["name"]), exporter.export(board)))
    return result


def load_manifest(path: Path) -> dict[str, Any]:
    with open(path, "r", encoding="utf-8") as handle:
        manifest = json.load(handle)
    if not isinstance(manifest.get("files"), list):
        raise SnapshotError(f"{path}: expected a 'files' list")
    for entry in manifest["files"]:
        if not entry.get("file") or not entry.get("boards"):
            raise SnapshotError(f"{path}: every file entry needs 'file' and 'boards'")
    return manifest


def build_file(snapshot: Snapshot, page: dict[str, Any], entry: dict[str, Any], snapshot_date: str) -> str:
    exported = export_boards(snapshot, page, list(entry["boards"]))
    blocks = [render_board(name, elements) for name, elements in exported]
    return render_file(str(page["name"]), snapshot_date, entry.get("description"), blocks)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("snapshot", type=Path, help="Penpot get-file JSON (kept outside the repository)")
    ap.add_argument("--page", default=DEFAULT_PAGE, help="page name prefix (default %(default)r)")
    ap.add_argument("--list", action="store_true", help="list the top-level boards and exit")
    ap.add_argument("--manifest", type=Path, help="JSON manifest: files and the boards in each")
    ap.add_argument("--only", action="append", default=[], help="with --manifest: only this output file name")
    ap.add_argument("--out-dir", type=Path, default=Path("data/ui/layout"), help="output directory")
    ap.add_argument("--board", action="append", default=[], help="export this board (name, number or name prefix)")
    ap.add_argument("--out", type=Path, help="with --board: write one file here")
    ap.add_argument("--stdout", action="store_true", help="with --board: print the board blocks")
    ap.add_argument("--snapshot-date", default=DEFAULT_SNAPSHOT_DATE, help="date written into the file header")
    args = ap.parse_args(argv)
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8")  # Cyrillic board names on a legacy Windows console

    try:
        snapshot = Snapshot.load(args.snapshot)
        page = snapshot.page(args.page)
        if args.list:
            for index, board in enumerate(BoardExporter(snapshot, page).top_level_boards()):
                print(f"{index:3d}  {rnd(board['width']):g}x{rnd(board['height']):g}  {board['name']}")
            return 0
        if args.manifest:
            manifest = load_manifest(args.manifest)
            args.out_dir.mkdir(parents=True, exist_ok=True)
            for entry in manifest["files"]:
                if args.only and entry["file"] not in args.only:
                    continue
                text = build_file(snapshot, page, entry, args.snapshot_date)
                target = args.out_dir / entry["file"]
                with open(target, "w", encoding="utf-8", newline="\n") as handle:
                    handle.write(text)
                print(f"{target}: {len(entry['boards'])} boards, {len(text)} bytes")
            return 0
        if args.board:
            exported = export_boards(snapshot, page, args.board)
            blocks = [render_board(name, elements) for name, elements in exported]
            text = render_file(str(page["name"]), args.snapshot_date, None, blocks)
            if args.out:
                with open(args.out, "w", encoding="utf-8", newline="\n") as handle:
                    handle.write(text)
            if args.stdout or not args.out:
                print("\n\n".join(blocks))
            return 0
        ap.error("give --list, --manifest or --board")
    except (SnapshotError, OSError, json.JSONDecodeError) as exc:
        print(f"penpot_export: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
