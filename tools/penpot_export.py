# Rendering
# --------------------------------------------------------------------------------------------------

def render_element(el: dict[str, Any]) -> str:
    parts: list[str] = []
    for key in ORDER:
        if key not in el or el[key] is None:
            continue
        value = el[key]
        if key == "t":
            parts.append("t = " + str(value))
        elif key in ("fs", "fw", "lh", "ls"):
            parts.append(f"{key} = " + (quote(value) if isinstance(value, str) else num(value)))
        elif key in ("ta", "va", "tt", "td", "fst", "grow"):
            parts.append(f"{key} = " + bare_or_quoted(str(value)))
        elif key in ("flex", "grid", "lc"):
            items = []
            for k, v in value.items():
                if v is None:
                    continue
                if isinstance(v, str) and IDENT.match(v):
                    items.append(f"{k} = {v}")
                else:
                    items.append(f"{k} = {pd_value(v)}")
            parts.append(f"{key} = {{ " + " ".join(items) + " }")
        elif key == "s":
            items = []
            for stroke in value:
                inner = []
                for k, v in stroke.items():
                    if k in ("a", "st", "cap") and isinstance(v, str):
                        inner.append(f"{k} = " + bare_or_quoted(v))
                    else:
                        inner.append(f"{k} = " + pd_value(v))
                items.append("{ " + " ".join(inner) + " }")
            parts.append("s = [" + " ".join(items) + "]")
        elif key == "sh":
            items = []
            for shadow in value:
                inner = []
                for k, v in shadow.items():
                    if k == "st" and isinstance(v, str):
                        inner.append(f"{k} = " + bare_or_quoted(v))
                    else:
                        inner.append(f"{k} = " + pd_value(v))
                items.append("{ " + " ".join(inner) + " }")
            parts.append("sh = [" + " ".join(items) + "]")
        elif key == "f":
            parts.append("f = [" + " ".join(pd_value(v) for v in value) + "]")
        else:
            parts.append(f"{key} = " + pd_value(value))
    return "    { " + " ".join(parts) + " }"


def render_board(name: str, elements: list[dict[str, Any]]) -> str:
    root = elements[0]
    lines = [f"board {quote(name)} {{", f"  w = {num(root['w'])} h = {num(root['h'])}", "  el = ["]
    lines.extend(render_element(el) for el in elements)
    lines.append("  ]")
    lines.append("}")
    return "\n".join(lines)


def render_file(page_name: str, snapshot_date: str, description: str | None, board_blocks: list[str]) -> str:
    lines = [
        "format_version = 1",
        '# Exact geometry exported from the Penpot file "Patriarch Design UX/UI", '
        f'page "{page_name}" (snapshot {snapshot_date}).',
    ]
    if description:
        lines.append("# " + description)
    return "\n".join(lines) + "\n" + LEGEND + "\n" + "\n\n".join(board_blocks) + "\n"


