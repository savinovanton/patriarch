#!/usr/bin/env python3
"""Penpot snapshot -> data/ui/layout/*.pd exporter (UI-D11).

Reads a local JSON snapshot of the owner's Penpot file (the backend `get-file` response, kept OUTSIDE the
repository: it weighs tens of megabytes) and writes the exact board geometry in the `.pd` layout format of
docs/dev/ui-design.md section 12 (same keys as the plugin-based export that produced board_00..13).

Pure standard library, no network and no access tokens: the owner re-downloads the file with their own tooling
and the agent only runs this script on the downloaded JSON. Run it isolated:

    python -I tools/penpot_export.py <snapshot.json> --list
    python -I tools/penpot_export.py <snapshot.json> --manifest tools/penpot_layouts.json --out-dir data/ui/layout
    python -I tools/penpot_export.py <snapshot.json> --board "03 / " --stdout     # one board, for a diff

Never write a token, a share link or a user id into a layout file, a comment or a commit message.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any, Iterable

ROOT_ID = "00000000-0000-0000-0000-000000000000"

DEFAULT_PAGE = "00"
DEFAULT_SNAPSHOT_DATE = "2026-11-13"

IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

# Key order of one element (same as the committed files).
ORDER = (
    "n", "t", "x", "y", "w", "h", "f", "s", "r", "rc", "sh", "bl", "op", "rot",
    "txt", "ff", "fs", "fw", "lh", "ls", "ta", "va", "tt", "td", "fst", "grow",
    "flex", "grid", "lc", "inst", "main", "paths", "clip",
)

TYPE_NAMES = {
    "frame": "board",
    "rect": "rectangle",
    "circle": "ellipse",
    "text": "text",
    "group": "group",
    "path": "path",
    "bool": "path",
    "svg-raw": "path",
    "image": "image",
}

LEGEND = """\
# Each board lists its visible layers depth-first (hidden layers and icon internals are skipped).
# Keys: n layer name, t type, x y offset from the board's top-left in px at the 1920x1080 reference, w h size,
# f fills (hex[@opacity] | img:name | gradient block), s strokes (c colour, w width, a align, cap line cap), r radius, rc per-corner radii (tl tr br bl),
# sh shadows, bl layer blur, op opacity, rot rotation, txt text, ff font family, fs size, fw weight, lh line height multiplier (omitted when 1.35),
# ls letter spacing, ta text align, va vertical align, tt text transform, grow text grow type, flex/grid auto-layout
# (dir wrap ai jc ac rg cg pad[t r b l] hs vs), lc layout-child (hs vs as abs m[t r b l]), inst/main component instance or main,
# paths number of vector paths in a collapsed Icon group, clip 0 when the board does not clip its content.
# A text layer with no n is named by its own text. Format: docs/dev/ui-design.md. Generated by tools/penpot_export.py: do not edit by hand.
"""


# --------------------------------------------------------------------------------------------------
# Number and string formatting
# --------------------------------------------------------------------------------------------------

def num(value: Any) -> str:
    """A number in the .pd syntax: integers stay integers, others keep at most two decimals."""
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, str):
        value = float(value)
    rounded = round(float(value), 2)
    if rounded == int(rounded):
        return str(int(rounded))
    return f"{rounded:.2f}".rstrip("0").rstrip(".")


def rnd(value: Any) -> float:
    return round(float(value), 2)


def esc(text: str) -> str:
    return (
        text.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\t", "\\t")
        .replace("\r", "\\r")
    )


def quote(text: str) -> str:
    return '"' + esc(text) + '"'


def bare_or_quoted(text: str) -> str:
    return text if IDENT.match(text) else quote(text)


def pd_value(value: Any) -> str:
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, (int, float)):
        return num(value)
    if isinstance(value, str):
        return quote(value)
    if isinstance(value, (list, tuple)):
        return "[" + " ".join(pd_value(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{ " + " ".join(f"{k} = {pd_value(v)}" for k, v in value.items() if v is not None) + " }"
    return quote(str(value))


# --------------------------------------------------------------------------------------------------
# Snapshot access
# --------------------------------------------------------------------------------------------------

class SnapshotError(Exception):
    pass


class Snapshot:
    """A loaded Penpot file: the page index and the component table."""

    def __init__(self, data: dict[str, Any]) -> None:
        try:
            body = data["data"]
            self.pages: dict[str, Any] = body["pagesIndex"]
        except (KeyError, TypeError) as exc:
            raise SnapshotError("not a Penpot get-file snapshot: no data.pagesIndex") from exc
        self.components: dict[str, Any] = body.get("components") or {}
        self.file_name: str = str(data.get("name", "Penpot file"))

    @classmethod
    def load(cls, path: Path) -> "Snapshot":
        with open(path, "r", encoding="utf-8") as handle:
            return cls(json.load(handle))

    def page(self, prefix: str) -> dict[str, Any]:
        found = [p for p in self.pages.values() if str(p.get("name", "")).startswith(prefix)]
        if not found:
            raise SnapshotError(f"no page whose name starts with {prefix!r}")
        if len(found) > 1:
            names = ", ".join(repr(p["name"]) for p in found)
            raise SnapshotError(f"page prefix {prefix!r} is ambiguous: {names}")
        return found[0]


# --------------------------------------------------------------------------------------------------
# Shape -> element
# --------------------------------------------------------------------------------------------------

def color_string(color: str, opacity: Any) -> str:
    if opacity is None or float(opacity) == 1.0:
        return color
    return f"{color}@{num(opacity)}"


def fill_value(fill: dict[str, Any]) -> Any:
    image = fill.get("fillImage")
    if image:
        return "img:" + str(image.get("name") or "image")
    gradient = fill.get("fillColorGradient")
    if gradient:
        stops = []
        for stop in gradient.get("stops", []):
            stops.append(
                color_string(str(stop.get("color", "")), stop.get("opacity")) + "/" + num(stop.get("offset", 0))
            )
        return {
            "grad": str(gradient.get("type", "linear")),
            "sx": rnd(gradient.get("startX", 0)),
            "sy": rnd(gradient.get("startY", 0)),
            "ex": rnd(gradient.get("endX", 0)),
            "ey": rnd(gradient.get("endY", 0)),
            "stops": stops,
        }
    color = fill.get("fillColor")
    if color is None:
        return None
    return color_string(str(color), fill.get("fillOpacity"))


def fills_of(fills: Iterable[dict[str, Any]] | None) -> list[Any]:
    out = []
    for fill in fills or []:
        if fill.get("hidden"):
            continue
        value = fill_value(fill)
        if value is not None:
            out.append(value)
    return out


def strokes_of(strokes: Iterable[dict[str, Any]] | None) -> list[dict[str, Any]]:
    out = []
    for stroke in strokes or []:
        if stroke.get("hidden"):
            continue
        item: dict[str, Any] = {}
        if stroke.get("strokeColorGradient"):
            item["c"] = "gradient"
        else:
            item["c"] = color_string(str(stroke.get("strokeColor", "")), stroke.get("strokeOpacity"))
        item["w"] = rnd(stroke.get("strokeWidth", 1))
        align = stroke.get("strokeAlignment")
        if align and align != "center":
            item["a"] = align
        style = stroke.get("strokeStyle")
        if style and style != "solid":
            item["st"] = style
        cap = stroke.get("strokeCapStart")
        if cap:
            item["cap"] = cap
        out.append(item)
    return out


def shadows_of(shadows: Iterable[dict[str, Any]] | None) -> list[dict[str, Any]]:
    out = []
    for shadow in shadows or []:
        if shadow.get("hidden"):
            continue
        color = shadow.get("color") or {}
        out.append(
            {
                "st": shadow.get("style", "drop-shadow"),
                "x": rnd(shadow.get("offsetX", 0)),
                "y": rnd(shadow.get("offsetY", 0)),
                "b": rnd(shadow.get("blur", 0)),
                "sp": rnd(shadow.get("spread", 0)),
                "c": color_string(str(color.get("color", "")), color.get("opacity")),
            }
        )
    return out


def geometry(shape: dict[str, Any]) -> tuple[float, float, float, float]:
    """x y width height; vector paths carry no own geometry in the file, only a selection rectangle."""
    sel = shape.get("selrect") or {}
    values = []
    for key in ("x", "y", "width", "height"):
        value = shape.get(key)
        if value is None:
            value = sel.get(key, 0)
        values.append(float(value))
    return values[0], values[1], values[2], values[3]


def radii_of(shape: dict[str, Any]) -> tuple[float | None, list[float] | None]:
    """(r, rc): a single radius when the four corners agree, else the per-corner list (tl tr br bl)."""
    corners = [rnd(shape.get(k, 0) or 0) for k in ("r1", "r2", "r3", "r4")]
    if not any(corners):
        return None, None
    if len(set(corners)) == 1:
        return corners[0], None
    return None, corners


def text_runs(content: dict[str, Any]) -> tuple[list[list[dict[str, Any]]], str]:
    """The text leaves grouped by paragraph and the vertical alignment of the text root."""
    paragraphs: list[list[dict[str, Any]]] = []
    vertical = str(content.get("verticalAlign", "top")) if isinstance(content, dict) else "top"

    def walk(node: dict[str, Any], current: list[dict[str, Any]] | None) -> None:
        kind = node.get("type")
        if kind == "paragraph":
            leaves: list[dict[str, Any]] = []
            for child in node.get("children", []):
                if "text" in child:
                    leaves.append({**{k: v for k, v in node.items() if k != "children"}, **child})
                else:
                    walk(child, leaves)
            paragraphs.append(leaves)
            return
        if current is not None and "text" in node:
            current.append(node)
            return
        for child in node.get("children", []):
            walk(child, current)

    if isinstance(content, dict):
        walk(content, None)
    return paragraphs, vertical


def _all_same(values: list[Any]) -> bool:
    return all(v == values[0] for v in values)


def text_attrs(shape: dict[str, Any]) -> dict[str, Any]:
    paragraphs, vertical = text_runs(shape.get("content") or {})
    leaves = [leaf for para in paragraphs for leaf in para]
    out: dict[str, Any] = {}
    out["txt"] = "\n".join("".join(str(leaf.get("text", "")) for leaf in para) for para in paragraphs)
    if not leaves:
        return out

    def attr(key: str, default: Any = None) -> Any:
        values = [leaf.get(key, default) for leaf in leaves]
        return values[0] if _all_same(values) else "mixed"

    family = attr("fontFamily")
    if family:
        out["ff"] = family
    size = attr("fontSize")
    if size not in (None, "mixed"):
        out["fs"] = float(size)
    elif size == "mixed":
        out["fs"] = "mixed"
    weight = attr("fontWeight")
    if weight not in (None, "mixed"):
        out["fw"] = float(weight)
    elif weight == "mixed":
        out["fw"] = "mixed"
    line_height = attr("lineHeight")
    if line_height is not None:
        out["lh"] = line_height if line_height == "mixed" else float(line_height)
    spacing = attr("letterSpacing")
    if spacing is not None:
        out["ls"] = spacing if spacing == "mixed" else float(spacing)
    align = attr("textAlign")
    if align:
        out["ta"] = align
    if vertical:
        out["va"] = vertical
    transform = attr("textTransform")
    if transform:
        out["tt"] = transform
    decoration = attr("textDecoration")
    if decoration:
        out["td"] = decoration
    style = attr("fontStyle")
    if style:
        out["fst"] = style
    # Text fills come from the leaves (the shape's own fills are empty for text).
    leaf_fills = leaves[0].get("fills") or []
    out["_fills"] = fills_of(leaf_fills)
    return out


def flex_of(shape: dict[str, Any]) -> dict[str, Any]:
    gap = shape.get("layoutGap") or {}
    pad = shape.get("layoutPadding") or {}
    return {
        "dir": shape.get("layoutFlexDir", "row"),
        "wrap": shape.get("layoutWrapType", "nowrap"),
        "ai": shape.get("layoutAlignItems", "start"),
        "jc": shape.get("layoutJustifyContent", "start"),
        "ac": shape.get("layoutAlignContent", "stretch"),
        "rg": rnd(gap.get("rowGap", 0) or 0),
        "cg": rnd(gap.get("columnGap", 0) or 0),
        "pad": [rnd(pad.get(k, 0) or 0) for k in ("p1", "p2", "p3", "p4")],
        "hs": shape.get("layoutItemHSizing", "fix"),
        "vs": shape.get("layoutItemVSizing", "fix"),
    }


def grid_of(shape: dict[str, Any]) -> dict[str, Any]:
    gap = shape.get("layoutGap") or {}
    pad = shape.get("layoutPadding") or {}

    def track(item: dict[str, Any]) -> str:
        value = item.get("value")
        return str(item.get("type", "")) + ":" + ("" if value is None else num(value))

    return {
        "dir": shape.get("layoutGridDir", "row"),
        "rg": rnd(gap.get("rowGap", 0) or 0),
        "cg": rnd(gap.get("columnGap", 0) or 0),
        "pad": [rnd(pad.get(k, 0) or 0) for k in ("p1", "p2", "p3", "p4")],
        "rows": [track(r) for r in shape.get("layoutGridRows", []) or []],
        "cols": [track(c) for c in shape.get("layoutGridColumns", []) or []],
    }


def layout_child_of(shape: dict[str, Any]) -> dict[str, Any] | None:
    """Layout-child parameters, only when the parent is an auto-layout container."""
    child: dict[str, Any] = {}
    hs = shape.get("layoutItemHSizing")
    vs = shape.get("layoutItemVSizing")
    if hs and hs != "fix":
        child["hs"] = hs
    if vs and vs != "fix":
        child["vs"] = vs
    align = shape.get("layoutItemAlignSelf")
    if align and align != "auto":
        child["as"] = align
    if shape.get("layoutItemAbsolute"):
        child["abs"] = 1
    margin = shape.get("layoutItemMargin") or {}
    margins = [rnd(margin.get(k, 0) or 0) for k in ("m1", "m2", "m3", "m4")]
    if any(margins):
        child["m"] = margins
    for key, name in (
        ("layoutItemMinW", "minWidth"),
        ("layoutItemMaxW", "maxWidth"),
        ("layoutItemMinH", "minHeight"),
        ("layoutItemMaxH", "maxHeight"),
    ):
        if shape.get(key) is not None:
            child[name] = rnd(shape[key])
    return child or None


class BoardExporter:
    """Turns one top-level frame of a page into the list of elements of a `board` block."""

    def __init__(self, snapshot: Snapshot, page: dict[str, Any]) -> None:
        self.snapshot = snapshot
        self.objects: dict[str, Any] = page["objects"]

    def top_level_boards(self) -> list[dict[str, Any]]:
        root = self.objects.get(ROOT_ID)
        if not root:
            return []
        return [self.objects[cid] for cid in root.get("shapes", []) if cid in self.objects]

    def children(self, shape: dict[str, Any]) -> list[dict[str, Any]]:
        return [self.objects[cid] for cid in shape.get("shapes", []) or [] if cid in self.objects]

    def component_name(self, shape: dict[str, Any]) -> tuple[str, str]:
        comp = self.snapshot.components.get(shape.get("componentId", ""))
        if not comp:
            return "?", ""
        return str(comp.get("name", "?")), str(comp.get("path", ""))

    def element(self, shape: dict[str, Any], origin: tuple[float, float], is_root: bool, in_layout: bool) -> dict[str, Any]:
        kind = TYPE_NAMES.get(str(shape.get("type")), str(shape.get("type")))
        el: dict[str, Any] = {"n": str(shape.get("name", "")), "t": kind}
        gx, gy, gw, gh = geometry(shape)
        if is_root:
            el.update(x=0, y=0)
        else:
            el.update(x=rnd(gx - origin[0]), y=rnd(gy - origin[1]))
        el.update(w=rnd(gw), h=rnd(gh))
        fills = fills_of(shape.get("fills"))
        strokes = strokes_of(shape.get("strokes"))
        if kind == "text":
            attrs = text_attrs(shape)
            fills = attrs.pop("_fills", fills)
            grow = shape.get("growType")
            if grow and grow != "fixed":
                attrs["grow"] = grow
            if attrs.get("ls") == 0:
                attrs.pop("ls")
            if attrs.get("lh") == 1.35:
                attrs.pop("lh")
            if attrs.get("ta") == "left":
                attrs.pop("ta")
            if attrs.get("va") == "top":
                attrs.pop("va")
            if attrs.get("tt") == "none":
                attrs.pop("tt")
            if attrs.get("td") == "none":
                attrs.pop("td")
            if attrs.get("fst") == "normal":
                attrs.pop("fst")
            text = attrs.get("txt", "")
            name = el["n"]
            # A text layer is named by its own text unless the designer renamed it.
            if text.replace("\n", " ").startswith(name[:20]):
                del el["n"]
            el.update(attrs)
        if fills:
            el["f"] = fills
        if strokes:
            el["s"] = strokes
        r, rc = radii_of(shape)
        if r is not None:
            el["r"] = r
        if rc is not None:
            el["rc"] = rc
        shadows = shadows_of(shape.get("shadow"))
        if shadows:
            el["sh"] = shadows
        blur = shape.get("blur")
        if isinstance(blur, dict) and not blur.get("hidden") and blur.get("value"):
            el["bl"] = rnd(blur["value"])
        opacity = shape.get("opacity")
        if opacity is not None and float(opacity) != 1.0:
            el["op"] = rnd(opacity)
        rotation = shape.get("rotation")
        if rotation:
            el["rot"] = rnd(rotation)
        layout = shape.get("layout")
        if layout == "flex":
            el["flex"] = flex_of(shape)
        elif layout == "grid":
            el["grid"] = grid_of(shape)
        if in_layout:
            child = layout_child_of(shape)
            if child:
                el["lc"] = child
        if shape.get("componentId"):
            name, path = self.component_name(shape)
            if shape.get("mainInstance"):
                if not is_root:
                    el["main"] = (path + " / " + name) if path else name
            elif shape.get("shapeRef"):
                el["inst"] = name
        if kind == "board" and shape.get("showContent"):
            el["clip"] = 0
        return el

    def visible_paths(self, group: dict[str, Any]) -> list[dict[str, Any]]:
        return [c for c in self.children(group) if c.get("type") == "path" and not c.get("hidden")]

    def export(self, board: dict[str, Any]) -> list[dict[str, Any]]:
        origin = geometry(board)[:2]
        out: list[dict[str, Any]] = []

        def walk(shape: dict[str, Any], is_root: bool, in_layout: bool) -> None:
            if shape.get("hidden"):
                return
            el = self.element(shape, origin, is_root, in_layout)
            if shape.get("type") == "group" and re.match(r"^Icon", str(shape.get("name", ""))):
                paths = self.visible_paths(shape)
                if paths:
                    el["paths"] = len(paths)
                    strokes = strokes_of(paths[0].get("strokes"))
                    if strokes:
                        el["s"] = strokes
                    fills = fills_of(paths[0].get("fills"))
                    if fills:
                        el["f"] = fills
                    out.append(el)
                    return
            out.append(el)
            container = shape.get("layout") in ("flex", "grid")
            for child in self.children(shape):
                walk(child, False, container)

        walk(board, True, False)
        return out


